#!/usr/bin/env node
/* Variant Surge eligibility coverage for Campaign (PR #679).
 *
 * Campaign judges a surged character in its active form. A form changes its eligibility only where
 * data/variant-form-research.js holds a reviewed, source-linked decision for that exact catalog form;
 * everywhere else it keeps its base character's classification. This report lists every catalog form,
 * which challenge decisions are reviewed, and which forms still have none (the follow-up worklist).
 * No network, no paid AI.
 *
 *   node tools/variant-eligibility-coverage.cjs --write   regenerate the report
 *   node tools/variant-eligibility-coverage.cjs --check   fail if the report is stale
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { loadGame } = require('./ability-audit-lib.cjs');
const { CAMPAIGN_VARIANTS } = require('../data/campaign-strategy.js');
const RESEARCH = require('../data/variant-form-research.js');

const ROOT = path.resolve(__dirname, '..');
const DOC = 'docs/variant-eligibility-coverage.md';
// Form-dependent Campaign challenges: abilities (tag rules) and form-dependent traits.
// Identity (women), talent pool, history and Underdogs stay with the base character by design.
const FORM_RULES = ['flight', 'magic', 'psychic', 'aquatic', 'fire', 'ice', 'electric', 'tech', 'stealth',
  'teleport', 'healing', 'giants', 'red', 'kids', 'mortal'];
// Decisions proposed during PR #679 that were not granted because no source settled them.
const PENDING = Object.freeze([
  ['dc:Batman|Devastator Batman', 'giants', 'Doomsday-virus hybrid; sources give 6’8”, below the eight-foot bar. Needs a scale feat.'],
  ['games:Bowser|Dreamy Bowser', 'magic', 'Dream Stone empowerment; not shown as spellcasting. Needs a ruling on artifact power.'],
  ['mcu:Wolverine|Hellverine (Logan)', 'magic', 'Demonic possession and hellfire; fire is granted, spellcasting is not shown.'],
  ['mcu:Wolverine|Phoenix Wolverine', 'flight', 'Far-future Phoenix host; no specific flight scene cited yet.']
]);

function coverage() {
  const game = loadGame();
  const live = new Set(game.roster.map(c => c.pool + ':' + c.n));
  const forms = [];
  for (const [base, list] of Object.entries(CAMPAIGN_VARIANTS)) {
    for (const f of list) {
      const key = base + '|' + f.name, rec = RESEARCH[key] || {};
      const reviewed = Object.fromEntries(Object.entries(rec)
        .filter(([t, d]) => FORM_RULES.includes(t) && (d.decision === 'yes' || d.decision === 'no'))
        .map(([t, d]) => [t, d.decision]));
      forms.push({ key, base, form: f.name, live: live.has(base), reviewed });
    }
  }
  forms.sort((a, b) => a.key.localeCompare(b.key));
  const orphanResearch = Object.keys(RESEARCH).filter(k => !forms.some(f => f.key === k)).sort();
  return { forms, orphanResearch, pending: PENDING };
}

function render(c) {
  const covered = c.forms.filter(f => Object.keys(f.reviewed).length);
  const open = c.forms.filter(f => !Object.keys(f.reviewed).length);
  const decisions = covered.reduce((n, f) => n + Object.keys(f.reviewed).length, 0);
  const notLive = c.forms.filter(f => !f.live);
  const byBase = new Map();
  for (const f of open) byBase.set(f.base, [...(byBase.get(f.base) || []), f.form]);
  const lines = [
    '# Variant Surge eligibility coverage', '',
    'Generated by `node tools/variant-eligibility-coverage.cjs --write`. Do not edit by hand.', '',
    'Campaign judges a surged character in the form it actually rolled. A form changes its eligibility only where',
    '`data/variant-form-research.js` records a reviewed, source-linked decision for that exact catalog form; for every',
    'other challenge it keeps its base character’s classification. Identity (Queens of the Court), talent pool, campaign',
    'history and The Underdogs always stay with the base character. Numerical challenges read the transformed attributes',
    'and need no record.', '',
    '## Summary', '',
    '| | Count |', '| --- | ---: |',
    '| Catalog forms | ' + c.forms.length + ' |',
    '| Forms with at least one reviewed decision | ' + covered.length + ' |',
    '| Reviewed form decisions | ' + decisions + ' |',
    '| Forms with no reviewed decision (follow-up) | ' + open.length + ' |',
    '| Forms whose base is missing from the live roster | ' + notLive.length + ' |',
    '| Research records that match no catalog form | ' + c.orphanResearch.length + ' |', '',
    '## Decisions held for review', '',
    'Proposed during PR #679 but not granted, because no source settled them. These forms keep their base classification.', '',
    '| Form | Challenge | Why it is held |', '| --- | --- | --- |',
    ...c.pending.map(([k, t, why]) => '| ' + k.replace('|', ' → ') + ' | ' + t + ' | ' + why + ' |'), '',
    '## Reviewed form decisions', '',
    '| Form | Qualifies | Does not qualify |', '| --- | --- | --- |',
    ...covered.map(f => {
      const yes = Object.entries(f.reviewed).filter(([, d]) => d === 'yes').map(([t]) => t).join(', ');
      const no = Object.entries(f.reviewed).filter(([, d]) => d === 'no').map(([t]) => t).join(', ');
      return '| ' + f.key.replace('|', ' → ') + ' | ' + (yes || '—') + ' | ' + (no || '—') + ' |';
    }), '',
    '## Forms with no reviewed decision (' + open.length + ')', '',
    'These inherit their base character’s eligibility for every form-dependent challenge until reviewed. Review each one for',
    'the abilities or traits it gains or loses (' + FORM_RULES.join(', ') + ').', '',
    '| Base character | Forms |', '| --- | --- |',
    ...[...byBase].map(([b, list]) => '| ' + b + ' | ' + list.join('; ') + ' |'), ''
  ];
  if (notLive.length) lines.push('## Forms whose base is not in the live roster', '', ...notLive.map(f => '- ' + f.key), '');
  if (c.orphanResearch.length) lines.push('## Research records that match no catalog form', '', ...c.orphanResearch.map(k => '- ' + k), '');
  return lines.join('\n');
}

function outputs() { return { [DOC]: render(coverage()) }; }

if (require.main === module) {
  const out = outputs();
  if (process.argv.includes('--write')) for (const [f, body] of Object.entries(out)) fs.writeFileSync(path.join(ROOT, f), body);
  else if (process.argv.includes('--check')) {
    const stale = Object.entries(out).filter(([f, body]) => !fs.existsSync(path.join(ROOT, f)) || fs.readFileSync(path.join(ROOT, f), 'utf8') !== body).map(([f]) => f);
    if (stale.length) { console.error('Out of date: ' + stale.join(', ') + '. Run --write.'); process.exit(1); }
    console.log('Variant eligibility coverage is current.');
  } else { console.log('Usage: --write or --check'); process.exit(2); }
}

module.exports = { coverage, outputs, render, DOC, FORM_RULES, PENDING };
