#!/usr/bin/env node
/* Character ability audit tool (read-only unless --write-index is passed).
     node tools/ability-audit.cjs --report        writes docs/character-ability-coverage.md
     node tools/ability-audit.cjs --write-index   regenerates CHARACTER_ABILITY_TAGS in
                                                  data/character-abilities.js
   The index is derived ONLY from explicit reviewed records: source-linked evidence in
   CHARACTER_ABILITIES plus the reviewed CHARACTER_ABILITY_CARRYOVER list, minus every power in
   CHARACTER_ABILITY_DISPUTES with verdict 'incorrect'. It never runs the Campaign engine, the
   CAMPAIGN_TAGS name lists or description/guide keyword matching, so regenerating it cannot
   reintroduce a keyword grant. Each broad tag is written with its specific tags (see
   tools/ability-tag-families.cjs). Review the diff before committing. */
const fs = require('node:fs');
const path = require('node:path');
const { ROOT, POOL_IDS, POWER_TAGS, loadGame } = require('./ability-audit-lib.cjs');
const { TAG_FAMILIES, classifySpecific } = require('./ability-tag-families.cjs');

const BEGIN = '/* BEGIN GENERATED ABILITY INDEX';
const END = '/* END GENERATED ABILITY INDEX */';

/** Reviewed tags per character, from records only. Returns {pool:{name:[broad, ...specific]}}. */
function derivedIndex(game) {
  const incorrect = new Set(game.disputes.filter(d => d.verdict === 'incorrect').map(d => d.id + '|' + d.tag));
  const index = {};
  for (const pool of POOL_IDS) index[pool] = {};
  for (const c of game.roster) {
    const tags = [];
    for (const broad of POWER_TAGS) {
      if (incorrect.has(c.id + '|' + broad)) continue;
      const specific = new Set();
      const rec = (game.abilities[c.id] || []).find(f => f.tag === broad);
      if (rec) classifySpecific(c.id, rec).forEach(t => specific.add(t));
      for (const x of game.carryover) if (x.id === c.id && x.tag === broad) x.tags.forEach(t => specific.add(t));
      if (!rec && !specific.size) continue;
      tags.push(broad, ...TAG_FAMILIES[broad].filter(t => specific.has(t)));
    }
    index[c.pool][c.n] = tags;
  }
  return index;
}

/** Provenance of every granted broad tag: 'evidence' or 'carry-over:<origin>'. */
function provenanceRows(game, index) {
  const rows = [];
  for (const c of game.roster) for (const tag of index[c.pool][c.n].filter(t => POWER_TAGS.includes(t))) {
    const rec = (game.abilities[c.id] || []).find(f => f.tag === tag);
    const carry = game.carryover.find(x => x.id === c.id && x.tag === tag);
    rows.push({ id: c.id, pool: c.pool, tag, basis: rec ? (rec.kind === 'role-based' ? 'evidence (role-based)' : 'evidence') : 'carry-over: ' + carry.origin });
  }
  return rows;
}

function writeIndex(game) {
  const index = derivedIndex(game);
  const lines = [BEGIN + ' (node tools/ability-audit.cjs --write-index).',
    '   Every roster character is listed, so [] means "audited: no qualifying power", not "unknown".',
    '   Each broad Campaign power id is followed by its specific tags (CHARACTER_ABILITY_TAG_FAMILIES).',
    '   Derived only from CHARACTER_ABILITIES evidence and CHARACTER_ABILITY_CARRYOVER, minus incorrect',
    '   disputes; characterAbilityProvenance() tells the two apart. Challenge criteria read this index. */',
    'const CHARACTER_ABILITY_TAGS = Object.freeze({'];
  for (const pool of POOL_IDS) {
    lines.push('  ' + pool + ': Object.freeze({');
    for (const [name, tags] of Object.entries(index[pool])) {
      lines.push('    ' + JSON.stringify(name) + ': ' + JSON.stringify(tags).replace(/,/g, ', ') + ',');
    }
    lines.push('  }),');
  }
  lines.push('});', END);
  const file = path.join(ROOT, 'data/character-abilities.js');
  const src = fs.readFileSync(file, 'utf8');
  const a = src.indexOf(BEGIN), b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error('Index markers not found in data/character-abilities.js');
  fs.writeFileSync(file, src.slice(0, a) + lines.join('\n') + src.slice(b + END.length));
  console.log('Wrote index for', game.roster.length, 'characters');
}

function report(game) {
  const index = derivedIndex(game);
  const prov = provenanceRows(game, index);
  const L = [];
  const pools = POOL_IDS;
  L.push('# Character ability coverage (generated)', '',
    'Generated by `node tools/ability-audit.cjs --report` from the reviewed index in `data/character-abilities.js`.',
    'The index is built only from explicit records (source-linked evidence plus reviewed carry-overs), never from',
    'name lists or description keywords. Counts are characters holding each broad tag.', '');
  L.push('## Characters by pool and broad tag', '', '| Tag | ' + pools.join(' | ') + ' | Total |', '| --- |' + pools.map(() => ' ---: |').join('') + ' ---: |');
  for (const tag of POWER_TAGS) {
    const n = p => game.roster.filter(c => (!p || c.pool === p) && index[c.pool][c.n].includes(tag)).length;
    L.push('| ' + tag + ' | ' + pools.map(n).join(' | ') + ' | ' + n(null) + ' |');
  }
  L.push('', '## Specific tags', '', '| Broad | Specific tag | Characters |', '| --- | --- | ---: |');
  for (const [broad, list] of Object.entries(TAG_FAMILIES)) for (const t of list) {
    L.push('| ' + broad + ' | ' + t + ' | ' + game.roster.filter(c => index[c.pool][c.n].includes(t)).length + ' |');
  }
  L.push('', '## Provenance of every granted broad tag', '', '| Pool | Evidence | Evidence (role-based) | Carry-over | Total |', '| --- | ---: | ---: | ---: | ---: |');
  for (const pool of pools) {
    const r = prov.filter(x => x.pool === pool);
    const ev = r.filter(x => x.basis === 'evidence').length, role = r.filter(x => x.basis === 'evidence (role-based)').length;
    L.push('| ' + pool + ' | ' + ev + ' | ' + role + ' | ' + (r.length - ev - role) + ' | ' + r.length + ' |');
  }
  const origins = {};
  for (const x of prov.filter(x => x.basis.startsWith('carry-over'))) origins[x.basis] = (origins[x.basis] || 0) + 1;
  L.push('', 'Carry-over origins: ' + Object.entries(origins).map(([k, v]) => k.replace('carry-over: ', '') + ' ' + v).join(', ') + '.');
  const records = Object.values(game.abilities).reduce((n, list) => n + list.length, 0);
  L.push('', '`CHARACTER_ABILITIES` holds ' + records + ' source-linked records for ' + Object.keys(game.abilities).length +
    ' characters; `CHARACTER_ABILITY_CARRYOVER` holds ' + game.carryover.length + ' reviewed carry-overs.', '');
  L.push('## Disputed grants (verdict incorrect: excluded from the index)', '');
  for (const d of game.disputes) L.push('- `' + d.id + '` **' + d.tag + '** (' + d.verdict + '): ' + d.reason);
  L.push('', '## Research queue (not granted; needs evidence or an owner ruling)', '');
  for (const q of game.research) L.push('- `' + q.id + '` **' + q.tag + '**: ' + q.note);
  L.push('', '## Non-NBA characters with no qualifying power', '');
  for (const pool of pools.filter(p => p !== 'nba')) {
    const none = game.roster.filter(c => c.pool === pool && !index[c.pool][c.n].length).map(c => c.n);
    L.push('- **' + pool + '** (' + none.length + '): ' + (none.join(', ') || '—'));
  }
  fs.writeFileSync(path.join(ROOT, 'docs/character-ability-coverage.md'), L.join('\n') + '\n');
  console.log('Wrote docs/character-ability-coverage.md');
}

if (require.main === module) {
  const game = loadGame();
  if (process.argv.includes('--write-index')) writeIndex(game);
  if (process.argv.includes('--report')) report(game);
  if (!process.argv.slice(2).length) console.log('Usage: --report and/or --write-index');
}
module.exports = { derivedIndex, provenanceRows };
