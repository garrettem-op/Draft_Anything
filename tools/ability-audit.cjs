#!/usr/bin/env node
/* Character ability audit tool (read-only unless --write-index is passed).
     node tools/ability-audit.cjs --report        writes docs/character-ability-coverage.md
     node tools/ability-audit.cjs --write-index   regenerates CHARACTER_ABILITY_TAGS in
                                                  data/character-abilities.js
   The index is derived from every bundled evidence layer the game already trusts, minus
   any power listed in CHARACTER_ABILITY_DISPUTES with verdict 'incorrect'. Review the diff
   before committing: the index is meant to be read by people and by challenge criteria. */
const fs = require('node:fs');
const path = require('node:path');
const { ROOT, POOL_IDS, POWER_TAGS, loadGame, engineMatrix } = require('./ability-audit-lib.cjs');

const BEGIN = '/* BEGIN GENERATED ABILITY INDEX';
const END = '/* END GENERATED ABILITY INDEX */';

function derivedIndex(game, matrix) {
  const incorrect = new Set(game.disputes.filter(d => d.verdict === 'incorrect').map(d => d.id + '|' + d.tag));
  const index = {};
  for (const pool of POOL_IDS) index[pool] = {};
  for (const c of game.roster) {
    index[c.pool][c.n] = POWER_TAGS.filter(t => matrix.get(c.id)[t] && !incorrect.has(c.id + '|' + t));
  }
  return index;
}

function writeIndex(game, matrix) {
  const index = derivedIndex(game, matrix);
  const lines = [BEGIN + ' (node tools/ability-audit.cjs --write-index).',
    '   Every roster character is listed, so [] means "audited: no qualifying power", not "unknown".',
    '   Tags use the 12 Campaign power ids. Evidence lives in CHARACTER_ABILITIES and the other',
    '   bundled layers; this index is the reviewed summary challenge criteria can reference. */',
    'const CHARACTER_ABILITY_TAGS = Object.freeze({'];
  for (const pool of POOL_IDS) {
    lines.push('  ' + pool + ': Object.freeze({');
    for (const [name, tags] of Object.entries(index[pool])) {
      lines.push('    ' + JSON.stringify(name) + ': ' + JSON.stringify(tags).replace(/,/g, ', ') + ',');
    }
    lines.push('  }),');
  }
  lines.push('});', END);
  const file = path.join(ROOT, 'data/character-abilities.js');
  const src = fs.readFileSync(file, 'utf8');
  const a = src.indexOf(BEGIN), b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error('Index markers not found in data/character-abilities.js');
  fs.writeFileSync(file, src.slice(0, a) + lines.join('\n') + src.slice(b + END.length));
  console.log('Wrote index for', game.roster.length, 'characters');
}

function report(game, matrix) {
  const L = [];
  const count = (pool, tag, pred = () => true) => game.roster.filter(c =>
    (!pool || c.pool === pool) && matrix.get(c.id)[tag] && pred(matrix.get(c.id)[tag])).length;
  L.push('# Character ability coverage (generated)', '',
    'Generated by `node tools/ability-audit.cjs --report` from the bundled roster and evidence layers.',
    'Counts are characters the live Campaign engine accepts for each power theme, with no network or paid AI.', '');
  L.push('## Accepted characters by pool and power', '',
    '| Power | ' + POOL_IDS.join(' | ') + ' | Total |', '| --- |' + POOL_IDS.map(() => ' ---: |').join('') + ' ---: |');
  for (const tag of POWER_TAGS) {
    L.push('| ' + tag + ' | ' + POOL_IDS.map(p => count(p, tag)).join(' | ') + ' | ' + count(null, tag) + ' |');
  }
  const layers = {};
  for (const row of matrix.values()) for (const l of Object.values(row)) layers[l] = (layers[l] || 0) + 1;
  L.push('', '## Evidence layer that grants each accepted character–power pair', '',
    '| Layer | Pairs |', '| --- | ---: |',
    ...Object.entries(layers).sort((a, b) => b[1] - a[1]).map(([k, v]) => '| ' + k + ' | ' + v + ' |'));
  const records = Object.values(game.abilities).reduce((n, list) => n + list.length, 0);
  L.push('', '`CHARACTER_ABILITIES` holds ' + records + ' source-linked records for ' +
    Object.keys(game.abilities).length + ' characters.', '');
  L.push('## Disputed grants (engine accepts, audit disagrees or needs a ruling)', '');
  for (const d of game.disputes) L.push('- `' + d.id + '` **' + d.tag + '** (' + d.verdict + '): ' + d.reason);
  L.push('', '## Research queue (not granted; needs evidence or a design ruling)', '');
  for (const q of game.research) L.push('- `' + q.id + '` **' + q.tag + '**: ' + q.note);
  L.push('', '## Non-NBA characters with no qualifying power after audit', '',
    'An empty entry is a reviewed result, not a guarantee. Most are non-powered by design (e.g. Han Solo outside the cockpit, Kermit).', '');
  for (const pool of POOL_IDS.filter(p => p !== 'nba')) {
    const none = game.roster.filter(c => c.pool === pool && !Object.keys(matrix.get(c.id)).length).map(c => c.n);
    L.push('- **' + pool + '** (' + none.length + '): ' + (none.join(', ') || '—'));
  }
  fs.writeFileSync(path.join(ROOT, 'docs/character-ability-coverage.md'), L.join('\n') + '\n');
  console.log('Wrote docs/character-ability-coverage.md');
}

if (require.main === module) {
  const game = loadGame();
  const matrix = engineMatrix(game);
  if (process.argv.includes('--write-index')) writeIndex(game, matrix);
  if (process.argv.includes('--report')) report(game, matrix);
  if (!process.argv.slice(2).length) console.log('Usage: --report and/or --write-index');
}
module.exports = { derivedIndex };
